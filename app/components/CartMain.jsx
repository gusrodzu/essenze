import {useOptimisticCart} from '@shopify/hydrogen';
import {Link} from 'react-router';
import {useAside} from '~/components/Aside';
import {CartLineItem} from '~/components/CartLineItem';
import {CartSummary} from './CartSummary';
import styles from './CartMain.module.css';

/**
 * Returns a map of all line items and their children.
 * @param {CartLine[]} lines
 * @return {LineItemChildrenMap}
 */
function getLineItemChildrenMap(lines) {
  const children = {};
  for (const line of lines) {
    if ('parentRelationship' in line && line.parentRelationship?.parent) {
      const parentId = line.parentRelationship.parent.id;
      if (!children[parentId]) children[parentId] = [];
      children[parentId].push(line);
    }
    if ('lineComponents' in line) {
      const lineChildren = getLineItemChildrenMap(line.lineComponents);
      for (const [parentId, childIds] of Object.entries(lineChildren)) {
        if (!children[parentId]) children[parentId] = [];
        children[parentId].push(...childIds);
      }
    }
  }
  return children;
}

/**
 * The main cart component that displays the cart items and summary.
 * It is used by both the /cart route and the cart aside dialog.
 * @param {CartMainProps}
 */
export function CartMain({layout, cart: originalCart}) {
  // The useOptimisticCart hook applies pending actions to the cart
  // so the user immediately sees feedback when they modify the cart.
  const cart = useOptimisticCart(originalCart);

  const linesCount = Boolean(cart?.lines?.nodes?.length || 0);
  const withDiscount =
    cart &&
    Boolean(cart?.discountCodes?.filter((code) => code.applicable)?.length);
  
  const cartClassName = `${styles.cartMain} ${
    withDiscount ? styles.withDiscount : ''
  }`;
  
  const cartHasItems = cart?.totalQuantity ? cart.totalQuantity > 0 : false;
  const childrenMap = getLineItemChildrenMap(cart?.lines?.nodes ?? []);

  return (
    <section
      className={cartClassName}
      aria-label={layout === 'page' ? 'Página del carrito' : 'Carrito lateral'}
    >
      <CartEmpty hidden={linesCount} layout={layout} />
      
      <div className={styles.cartDetails}>
        <div className={styles.cartLinesWrapper}>
          <p id="cart-lines" className={styles.srOnly}>
            Artículos del carrito
          </p>
          <ul aria-labelledby="cart-lines" className={styles.cartLinesList}>
            {(cart?.lines?.nodes ?? []).map((line) => {
              // we do not render non-parent lines at the root of the cart
              if (
                'parentRelationship' in line &&
                line.parentRelationship?.parent
              ) {
                return null;
              }
              return (
                <CartLineItem
                  key={line.id}
                  line={line}
                  layout={layout}
                  childrenMap={childrenMap}
                />
              );
            })}
          </ul>
        </div>
        
        {cartHasItems && <CartSummary cart={cart} layout={layout} />}
      </div>
    </section>
  );
}

/**
 * @param {{
 *   hidden: boolean;
 *   layout?: CartMainProps['layout'];
 * }}
 */
function CartEmpty({hidden = false}) {
  const {close} = useAside();
  
  return (
    <div className={styles.cartEmpty} hidden={hidden}>
      <span className={styles.emptyEyebrow}>Tu selección</span>
      <h2>Tu carrito está listo para descubrir algo nuevo.</h2>
      <p>Explora la curaduría Essenze y agrega las fragancias que quieras comparar, regalar o hacer parte de tu colección.</p>
      <Link to="/collections/all" onClick={close} prefetch="viewport">
        Explorar fragancias →
      </Link>
    </div>
  );
}

